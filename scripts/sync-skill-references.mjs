// Keep authored shared guidance in one place while making each host-exported
// skill directory self-contained. No symlinks or references outside its bundle.
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../skills/', import.meta.url));
const check = process.argv.includes('--check');
for (const name of (await readdir(root)).filter(name => name.startsWith('knowledge-'))) {
  // Automation setup routes to ingestion skills; it does not publish content.
  if (name === 'knowledge-automation') continue;
  const files = name === 'knowledge-recall' ? ['conventions.md'] : ['conventions.md', 'publication.md'];
  if (['knowledge-meeting-ingest', 'knowledge-entities'].includes(name)) files.push('meeting-entity-example.md');
  for (const file of files) {
    const source = await readFile(path.join(root, 'shared', file), 'utf8');
    const content = '<!-- Generated by scripts/sync-skill-references.mjs; edit skills/shared/' + file + '. -->\n' +
      (name === 'knowledge-recall'
        ? source.replace('For writes, also read\n[publication.md](publication.md). ', '')
        : source);
    const target = path.join(root, name, 'references', file);
    if (check) {
      if (await readFile(target, 'utf8').catch(() => '') !== content) {
        throw Error(`Stale skill reference: ${name}/references/${file}; run npm run skills:sync`);
      }
    } else {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content);
    }
  }
}
